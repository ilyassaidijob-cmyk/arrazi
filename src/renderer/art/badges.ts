export function rankBadgeBuf(rank: number, tier: number, size: 'sm' | 'lg' = 'lg') {
  const W = 19;
  const H = 23;
  const b = new PixBuf(W + 2, H + 2);
  const inner = new PixBuf(W, H);
  const c = (W - 1) / 2;
  for (let y = 0; y < H; y++) {
    const half = y < 13 ? c : c * (1 - (y - 13) / 10);
    for (let x = 0; x < W; x++) {
      const dx = Math.abs(x - c);
      if (dx > half) continue;
      const edge = dx > half - 1.5 || y < 1.5;
      inner.set(x, y, edge ? (rank >= 8 ? 4 : 3) : 1);
    }
  }
  const em = RANK_EMBLEM[Math.max(0, Math.min(9, rank - 1))];
  inner.ascii(5, 3, em.map((r) => r.replace(/ /g, '.')));
  for (let i = 0; i < 3; i++) {
    const x = c - 3 + i * 3;
    inner.set(x, 13, i < tier ? 4 : 2);
    inner.set(x + 1, 13, i < tier ? 4 : 2);
    inner.set(x, 14, i < tier ? 3 : 2);
    inner.set(x + 1, 14, i < tier ? 3 : 2);
  }
  b.blit(inner, 1, 1);
  b.outline(0);
  void size;
  return b;
}

export function rankBadgeUrl(rank: number, tier: number) {
  return dataUrl(`rank:${rank}:${tier}`, () => rankBadgeBuf(rank, tier));
}
