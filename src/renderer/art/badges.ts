function frame(b: PixBuf, type: AchType) {
  const S = b.w;
  const c = (S - 1) / 2;
  for (let y = 0; y < S; y++)
    for (let x = 0; x < S; x++) {
      const dx = Math.abs(x - c);
      const dy = Math.abs(y - c);
      let inside = false;
      let edge = false;
      switch (type) {
        case 'Focus': {
          const d = Math.hypot(x - c, y - c);
          inside = d <= c + 0.3;
          edge = inside && d > c - 1.5;
          break;
        }
        case 'Learning': {
          const half = y < c ? c : c * (1 - (y - c) / (c + 1)) + 1;
          inside = dx <= half;
          edge = inside && (dx > half - 1.5 || y < 1.5);
          break;
        }
        case 'Streak': {
          inside = dx + dy <= c + 0.5;
          edge = inside && dx + dy > c - 1.5;
          break;
        }
        case 'Character': {
          inside = !(dx > c - 2 && dy > c - 2);
          edge = inside && (dx > c - 1.5 || dy > c - 1.5 || (dx > c - 3 && dy > c - 3));
          break;
        }
        case 'Special': {
          inside = dx + dy <= c * 1.4 && dx <= c && dy <= c;
          edge = inside && (dx + dy > c * 1.4 - 1.5 || dx > c - 1 || dy > c - 1);
          break;
        }
      }
      if (inside) b.set(x, y, edge ? 3 : 1);
    }
}

export function badgeBuf(id: string, type: AchType, locked: boolean, hidden = false): PixBuf {
  const S = 21;
  const b = new PixBuf(S + 2, S + 2);
  const inner = new PixBuf(S, S);
  frame(inner, type);
  if (hidden) {
    inner.ascii(7, 5, ['.444.', '4...4', '....4', '...4.', '..4..', '..4..', '.....', '..4..']);
  } else {
    const g = G[id];
    if (g) inner.ascii(5, 5, g.map((r) => r.slice(0, 11)));
  }
  if (locked) inner.map((c) => (c >= 3 ? 2 : c === 2 ? 1 : c));
  b.blit(inner, 1, 1);
  b.outline(0);
  return b;
}

export function badgeUrl(id: string, type: AchType, locked: boolean, hidden = false) {
  return dataUrl(`badge:${id}:${locked}:${hidden}`, () => badgeBuf(id, type, locked, hidden));
}

/** Moon challenge badge: a moon with the challenge's month phase */
export function challengeBadgeUrl(month: number, done: boolean) {
  return dataUrl(`chbadge:${month}:${done}`, () => {
    const S = 21;
    const b = new PixBuf(S + 2, S + 2);
    const c = 11;
    for (let y = 0; y < S + 2; y++)
      for (let x = 0; x < S + 2; x++) {
        const d = Math.hypot(x - c, y - c);
        if (d <= 10) b.set(x, y, d > 8.6 ? 3 : 1);
      }
    const phase = ((month % 12) + 1) / 12;
    for (let y = -6; y <= 6; y++) {
      const w = Math.sqrt(36 - y * y);
      for (let x = -6; x <= 6; x++) {
        if (x * x + y * y > 36) continue;
        b.set(c + x, c + y, x + 0.5 > (1 - 2 * phase) * w ? 4 : 2);
      }
    }
    if (!done) b.map((v) => (v >= 3 ? 2 : v === 2 ? 1 : v));
    b.outline(0);
    return b;
  });
}

