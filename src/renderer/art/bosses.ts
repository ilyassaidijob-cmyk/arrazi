export function bossBuf(id: string, hurt = false, dark = false): PixBuf {
  const rows = (B[id] ?? B.shadow)[0];
  const w = Math.max(...rows.map((r) => r.length));
  const b = new PixBuf(w + 2, rows.length + 2);
  b.ascii(1, 1, rows);
  if (hurt) b.map((c) => (c === 1 ? 3 : c === 2 ? 4 : c));
  if (dark) b.map((c) => (c >= 3 ? 2 : c === 2 ? 1 : c));
  b.outline(0);
  return b;
}

export function bossUrl(id: string, hurt = false, dark = false) {
  return dataUrl(`boss:${id}:${hurt}:${dark}`, () => bossBuf(id, hurt, dark));
}
