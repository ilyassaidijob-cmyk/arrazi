/** Procedural gear, cleaner than ASCII */
export function gearUrl() {
  return dataUrl('home:gear2', () => {
    const S = 24;
    const b = new PixBuf(S, S);
    const c = (S - 1) / 2;
    for (let y = 0; y < S; y++)
      for (let x = 0; x < S; x++) {
        const dx = x - c;
        const dy = y - c;
        const d = Math.hypot(dx, dy);
        const a = Math.atan2(dy, dx);
        const tooth = Math.cos(a * 8) > 0.35 ? 11.2 : 8.6;
        if (d <= tooth && d > 3.2) b.set(x, y, d < 5 ? 3 : d > tooth - 1.2 ? 3 : 4);
      }
    b.outline(1);
    return b;
  });
}
