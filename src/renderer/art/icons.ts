export type IconName = keyof typeof I;

export function iconBuf(name: string, shift = 0): PixBuf {
  const rows = I[name] ?? I.badge;
  const w = Math.max(...rows.map((r) => r.length));
  const b = new PixBuf(w, rows.length);
  b.ascii(0, 0, rows.map((r) => r.replace(/ /g, '.')));
  if (shift) b.map((c) => Math.max(0, Math.min(4, c + shift)));
  return b;
}

export function iconUrl(name: string, shift = 0) {
  return dataUrl(`icon:${name}:${shift}`, () => iconBuf(name, shift));
}

